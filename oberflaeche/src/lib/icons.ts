export function iconFuer(name: string | null | undefined): LucideIcon {
  if (!name) return Puzzle;
  const k = name
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .toLowerCase()
    .replace(/[\s_]+/g, '-');
  return KARTE[k] ?? KARTE[k.split('-')[0] ?? ''] ?? Puzzle;
}
